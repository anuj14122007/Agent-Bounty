"""Deterministic offline demonstration provider for AgentBounty specialist workers."""

from __future__ import annotations

import re
from decimal import Decimal
from statistics import mean, median
from typing import Any


class DemoAgentProvider:
    """Offline, deterministic demonstration provider requiring zero external API keys.

    Generates structured, predictable deliverables tailored to each specialist worker type.
    Outputs are explicitly labeled as demonstration artifacts and never claim live execution
    or external web retrieval.
    """

    DEMO_BANNER = "[DEMO MODE: Offline simulated deliverable generated by DemoAgentProvider]"

    def generate(
        self,
        prompt: str,
        system_prompt: str | None = None,
        context: dict[str, Any] | None = None,
    ) -> str:
        """Generate predictable text for general prompts in DEMO mode."""
        lines = [self.DEMO_BANNER]
        if system_prompt:
            lines.append(f"Persona: {system_prompt}")
        lines.append(f"Prompt Echo: {prompt.strip()}")
        lines.append("Response: Deterministic response generated for offline evaluation.")
        return "\n\n".join(lines)

    def generate_worker_deliverable(
        self,
        worker_name: str,
        task_title: str,
        task_description: str,
        acceptance_criteria: list[str],
        context: dict[str, Any] | None = None,
    ) -> tuple[str, dict[str, Any]]:
        """Generate structured deliverable text and metadata based on specialist worker specialization."""
        ctx = context or {}
        name_lower = worker_name.lower()

        if "writer" in name_lower or "creative" in name_lower:
            return self._generate_creative_writer_output(task_title, task_description, acceptance_criteria, ctx)
        elif "research" in name_lower:
            return self._generate_researcher_output(task_title, task_description, acceptance_criteria, ctx)
        elif "data" in name_lower or "analyst" in name_lower:
            return self._generate_data_analyst_output(task_title, task_description, acceptance_criteria, ctx)
        elif "code" in name_lower or "assistant" in name_lower or "developer" in name_lower:
            return self._generate_code_assistant_output(task_title, task_description, acceptance_criteria, ctx)
        else:
            return self._generate_generic_output(worker_name, task_title, task_description, acceptance_criteria, ctx)

    def _extract_criterion_values(self, acceptance_criteria: list[str], prefix: str) -> list[str]:
        """Helper to extract parameter values from criteria like contains:foo or has_section:bar."""
        results = []
        for crit in acceptance_criteria:
            crit_clean = crit.strip()
            if crit_clean.lower().startswith(prefix.lower()):
                val = crit_clean[len(prefix) :].strip()
                if val:
                    results.append(val)
        return results

    def _generate_creative_writer_output(
        self,
        task_title: str,
        task_description: str,
        acceptance_criteria: list[str],
        context: dict[str, Any],
    ) -> tuple[str, dict[str, Any]]:
        """Generate structured creative writing deliverable."""
        # Build structured sections
        sections = [
            self.DEMO_BANNER,
            f"# {task_title}",
            "## Introduction\n"
            f"Welcome to the formal overview for {task_title}. "
            f"{task_description.strip()} "
            "This deliverable provides a refined and engaging synthesis tailored to the project brief. "
            "Detailed narrative context is integrated to ensure tone and message alignment across all project facets.",
            "## Key Features & Highlights\n"
            "- Clear and accessible communication structured for target stakeholders.\n"
            "- Thoughtfully formatted messaging balancing technical precision with narrative flow.\n"
            "- Tailored tone emphasizing efficiency, accountability, and verified excellence.",
            "## Conclusion\n"
            f"In summary, this product document successfully satisfies the requirements outlined in {task_title}. "
            "The deliverable is formatted according to professional publication standards.",
        ]

        content = "\n\n".join(sections)
        word_count = len(content.split())
        metadata = {
            "provider": "demo",
            "worker_type": "creative_writer",
            "word_count": word_count,
            "char_count": len(content),
            "sections_generated": len(sections),
            "simulated": True,
        }
        return content, metadata

    def _generate_researcher_output(
        self,
        task_title: str,
        task_description: str,
        acceptance_criteria: list[str],
        context: dict[str, Any],
    ) -> tuple[str, dict[str, Any]]:
        """Generate structured research brief deliverable without claiming live internet access."""
        # Extract user-supplied sources
        provided_sources = context.get("sources", [])
        if not provided_sources:
            # Check if sources are mentioned in the task description
            url_matches = re.findall(r"https?://\S+", task_description)
            if url_matches:
                provided_sources = url_matches

        sources_block = (
            "\n".join([f"- Supplied Source: {src}" for src in provided_sources])
            if provided_sources
            else "- No external human sources supplied in task context."
        )

        sections = [
            self.DEMO_BANNER,
            "> NOTICE: This research brief was generated in offline demonstration mode. "
            "No live internet search, academic indexing, or live fact-checking was conducted. "
            "All findings are structured based strictly on provided task context and deterministic simulation.",
            f"# Research Brief: {task_title}",
            f"## Executive Summary\n"
            f"This research brief organizes the analytical requirements for '{task_title}'. "
            f"{task_description.strip()} "
            "It consolidates available evidentiary context and identifies key conceptual pillars.",
            "## Key Findings\n"
            "1. Domain Context: Requirements emphasize verifiable delegation and structured governance.\n"
            "2. Structural Dynamics: Task acceptance criteria must be explicitly machine-checkable.\n"
            "3. Operational Safety: Autonomous workflows require decoupled validation gates.",
            "## Missing Evidence & Information Gaps\n"
            "- Quantitative benchmarks under high-concurrency workloads have not been empirically verified.\n"
            "- Live external literature has not been fetched in this offline environment.",
            f"## Sources & References\n{sources_block}",
        ]

        content = "\n\n".join(sections)
        metadata = {
            "provider": "demo",
            "worker_type": "research_assistant",
            "word_count": len(content.split()),
            "external_search_performed": False,
            "simulated": True,
            "preserved_sources": provided_sources,
        }
        return content, metadata

    def _generate_data_analyst_output(
        self,
        task_title: str,
        task_description: str,
        acceptance_criteria: list[str],
        context: dict[str, Any],
    ) -> tuple[str, dict[str, Any]]:
        """Generate structured data analysis deliverable with actual mathematical calculations."""
        # Extract numeric data from context or task description
        raw_numbers: list[float] = []
        if "data" in context and isinstance(context["data"], (list, tuple)):
            for item in context["data"]:
                try:
                    raw_numbers.append(float(item))
                except (ValueError, TypeError):
                    continue

        if not raw_numbers:
            # Parse floating-point and integer numbers from task description
            found = re.findall(r"(?:(?<=\s)|(?<=^)|(?<=[(\[,:]))([+-]?\d+(?:\.\d+)?)(?=[)\]\s,;:]|$)", task_description)
            for item in found:
                try:
                    raw_numbers.append(float(item))
                except ValueError:
                    continue

        calc_stats: dict[str, Any] = {}
        if raw_numbers:
            n_count = len(raw_numbers)
            n_sum = round(sum(raw_numbers), 4)
            n_mean = round(mean(raw_numbers), 4)
            n_min = min(raw_numbers)
            n_max = max(raw_numbers)
            n_med = round(median(raw_numbers), 4)
            calc_stats = {
                "count": n_count,
                "sum": n_sum,
                "mean": n_mean,
                "min": n_min,
                "max": n_max,
                "median": n_med,
            }
            stats_table = (
                "| Metric | Calculated Value |\n"
                "|---|---|\n"
                f"| Sample Count (N) | {n_count} |\n"
                f"| Sum | {n_sum} |\n"
                f"| Arithmetic Mean | {n_mean} |\n"
                f"| Median | {n_med} |\n"
                f"| Minimum | {n_min} |\n"
                f"| Maximum | {n_max} |"
            )
            raw_sample_str = ", ".join(str(x) for x in raw_numbers[:10])
            if len(raw_numbers) > 10:
                raw_sample_str += f" ... (+{len(raw_numbers) - 10} more)"
        else:
            stats_table = (
                "> NOTICE: No numeric data array was detected in task input or context. "
                "Baseline descriptive schema presented below."
            )
            raw_sample_str = "None provided"

        sections = [
            self.DEMO_BANNER,
            f"# Data Analysis Report: {task_title}",
            "## Executive Summary\n"
            f"This quantitative analysis report compiles statistical metrics for '{task_title}'. "
            f"{task_description.strip()} "
            "Calculations are strictly computed from verified input numbers without fabricated distributions.",
            f"## Tabular Summary\n{stats_table}",
            "## Data Integrity & Methodological Observations\n"
            f"- Ingested Samples: `{raw_sample_str}`\n"
            "- Calculation Method: Exact Python standard arithmetic.\n"
            "- Fabrication Policy: Zero synthetic datapoints were fabricated.",
            "## Conclusion\n"
            "The computed indicators demonstrate stable distribution boundaries within the supplied sample.",
        ]

        content = "\n\n".join(sections)
        metadata = {
            "provider": "demo",
            "worker_type": "data_analyst",
            "word_count": len(content.split()),
            "calculated_stats": calc_stats,
            "data_sample_count": len(raw_numbers),
            "simulated": True,
        }
        return content, metadata

    def _generate_code_assistant_output(
        self,
        task_title: str,
        task_description: str,
        acceptance_criteria: list[str],
        context: dict[str, Any],
    ) -> tuple[str, dict[str, Any]]:
        """Generate structured technical code draft without executing arbitrary code."""
        # Generate a clean, typed Python implementation skeleton matching the title
        safe_fn_name = re.sub(r"[^a-zA-Z0-9_]", "_", task_title.lower()).strip("_")
        if not safe_fn_name or safe_fn_name[0].isdigit():
            safe_fn_name = f"solve_{safe_fn_name}"

        code_block = (
            "```python\n"
            '"""Implementation for: '
            f"{task_title}\n"
            '"""\n\n'
            "from __future__ import annotations\n\n"
            "from typing import Any\n\n\n"
            f"def {safe_fn_name}(*args: Any, **kwargs: Any) -> dict[str, Any]:\n"
            f'    """Execute technical logic for {task_title}.\n\n'
            f"    Note: Static code draft generated in offline demonstration mode.\n"
            '    """\n'
            '    result = {"status": "success", "task": "'
            f"{task_title}"
            '", "inputs": args}\n'
            "    return result\n"
            "```"
        )

        sections = [
            self.DEMO_BANNER,
            "> SECURITY NOTICE: Static code deliverable only. "
            "No shell commands, Python subprocesses, filesystem mutations, or network operations "
            "were executed to produce this code.",
            f"# Technical Implementation: {task_title}",
            "## Architecture Overview\n"
            f"This technical document provides the implementation specifications and code draft for '{task_title}'. "
            f"{task_description.strip()} "
            "The logic adheres to strict typing, modular boundaries, and predictable error handling.",
            f"## Implementation Code\n{code_block}",
            "## Verification & Testing Recommendations\n"
            "- Unit test coverage should validate boundary conditions and edge cases.\n"
            "- Ensure zero unhandled exceptions on malformed input data.\n"
            "- Verify static type checking with strict mypy settings.",
        ]

        content = "\n\n".join(sections)
        metadata = {
            "provider": "demo",
            "worker_type": "code_assistant",
            "word_count": len(content.split()),
            "language": "python",
            "arbitrary_execution_prevented": True,
            "simulated": True,
        }
        return content, metadata

    def _generate_generic_output(
        self,
        worker_name: str,
        task_title: str,
        task_description: str,
        acceptance_criteria: list[str],
        context: dict[str, Any],
    ) -> tuple[str, dict[str, Any]]:
        """Fallback deliverable generation for generic workers."""
        sections = [
            self.DEMO_BANNER,
            f"# Deliverable: {task_title}",
            f"Worker: {worker_name}",
            f"Task Description: {task_description}",
            "## Content\nTask requirements have been reviewed and structured deliverable completed.",
        ]
        content = "\n\n".join(sections)
        return content, {"provider": "demo", "worker": worker_name, "simulated": True}
